#!/usr/bin/env python3
"""generate_rooms_page.py — render the 16-room catalog into website/rooms/ (ZERO LLM).

Living-provenance pattern (same family as runbook_drift.py): the page is GENERATED
from pmoves/config/rooms/catalog.json — never hand-written. Stage badges follow the
P7 sourcing discipline (current_stage is real only via P7 transition writeback or
manifest declaration; 'typical-stage table' sourcing was withdrawn 2026-09-08).
Each room links to its manifest in the repo (window to the source).

Output: website/rooms/data.js (+ prints a summary). Re-run after catalog updates;
the weekly drift check can verify the page matches the catalog via its digest.
"""
import hashlib, json, time
from pathlib import Path

ROOT = Path('/a0/usr/projects/pmoves_ai')
CATALOG = ROOT / 'pmoves/config/rooms/catalog.json'
OUT_DIR = ROOT / 'website/rooms'
REPO_URL = 'https://github.com/POWERFULMOVES/PMOVES.AI/blob/main/pmoves/config/rooms'

def main():
    """Read catalog, digest it, emit data.js with rooms + provenance metadata."""
    raw = CATALOG.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    cat = json.loads(raw)
    rooms = cat['rooms']
    generated = time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
    live = [r for r in rooms if r.get('current_stage') == 'live']
    rehearsal = [r for r in rooms if r.get('current_stage') != 'live']
    data = {
        'generated_at': generated,
        'catalog_sha256': digest,
        'counts': {'total': len(rooms), 'live': len(live), 'rehearsal': len(rehearsal)},
        'rooms': [
            {
                'room_id': r['room_id'],
                'display_name': r['display_name'],
                'agent_id': r['agent_id'],
                'alter': r['alter'],
                'stage': r.get('current_stage', r.get('stage', 'rehearsal')),
                'summary': r['summary'],
                'manifest_url': f'https://github.com/POWERFULMOVES/PMOVES.AI/blob/main/pmoves/config/rooms/{r["manifest"]}',
            }
            for r in rooms
        ],
    }
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / 'data.js'
    out.write_text(
        '// GENERATED by scripts/generate_rooms_page.py from pmoves/config/rooms/catalog.json\n'
        f'// catalog sha256: {digest}\n'
        f'// generated_at: {generated}\n'
        '// Do not hand-edit — re-run the generator.\n'
        'window.PMOVES_ROOMS = ' + json.dumps(data, indent=1) + ';\n'
    )
    print(json.dumps({'out': str(out), 'rooms': len(rooms),
                      'live': len(live), 'rehearsal': len(rehearsal),
                      'digest': digest[:12]}))

if __name__ == '__main__':
    main()
