#!/usr/bin/env python3
"""Validate-composes ratchet.

No-network, <100ms scan of every `pmoves/docker-compose*.yml` file.
Fails (exit 1) on any of the operator-trust patterns below; the fix is
either convert to long form, drop the entry, or justify it in a
follow-up PR. The ratchet only goes DOWN over time — a fix that
re-introduces a straggler is caught immediately, not after the next
incidents-of-silence audit.

Patterns enforced (per PMOVES Mavis housekeeping batch 2026-08-03 +
the straggler sweep in PR #2415):

  1. env_file short-form `.env.local` — REQUIRED by default in
     docker-compose; hard-fails bring-up on nodes without the file.
     Fix: long-form `- path: .env.local / required: false`.
  2. env_file short-form with `env.shared` — same class of issue
     if a node doesn't have that file. Fix: long-form + required: false
     if it should be optional, or fix the bring-up to always create it.
  3. images without digest — fleet policy is digest-pinned for any
     image that runs in production. `latest`, semver tags, and
     non-digested refs all surface here so the operator sees the gap
     before the next "why is prod on a moving tag" incident.

This script reads a static set of YAML files in the repo. No GitHub
API, no fork-registry access, no token privilege. Runs in <100ms on
the full ~50-file overlay set.

Usage:
    python3 pmoves/tools/validate_composes.py
    python3 pmoves/tools/validate_composes.py --json
    python3 pmoves/tools/validate_composes.py --check-images
    python3 pmoves/tools/validate_composes.py --strict-env-shared

By default only env_file patterns are checked (the env.local
straggler shape from PR #2415). Pass --check-images to also flag
images without digest pinning — that's a fleet-policy ratchet, not
a "merged before the issue was addressed" ratchet, and produces a
lot of false-positive noise on overlays that haven't been migrated
yet.
"""

