def render_install_bash(tool: CliTool, identities: list[NodeIdentity]) -> str:
    """Generate the bash install script (rc function + PATH symlink)."""
    pin_block = _render_install_bash_pins(tool, identities)
    pin_block_functions = _render_install_bash_pin_functions(tool, identities)
    header = GENERATOR_HEADER_BASH.format(ver=GENERATOR_VERSION)
    pin_label_csv = ", ".join(f"{tool.launcher_basename}-{_pin_label(i)}" for i in identities) if identities else ""
    pin_install_echo = ""
    if pin_label_csv:
        pin_install_echo = f'echo "Also installed: {pin_label_csv}"\n'
    return f"""{header}
# install-{tool.name}-pmoves-command.sh
# ---------------------------------------------------------------------------
# Makes `{tool.launcher_basename}` a bare command in bash/zsh on THIS node, so
# you can type `{tool.launcher_basename}` from any directory instead of the full
# launcher path.  Also installs any per-node pin functions the registry
# describes for the `{tool.name}` family.
#
# Usage:
#   bash deploy/provision/install-{tool.launcher_basename}.sh
#
# Per-node pin functions (set PMOVES_NODE_ID before calling the launcher):
{pin_block}
# ---------------------------------------------------------------------------
set -euo pipefail

script_dir="$(cd "$(dirname "${{BASH_SOURCE[0]:-$0}}")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"
launcher="$repo_root/deploy/provision/{tool.launcher_basename}.sh"
[ -f "$launcher" ] || {{ echo "launcher not found: $launcher" >&2; exit 1; }}

# Refuse linked worktrees (same guard as install-claude-pmoves-command.sh:30-42):
# a worktree .git is a FILE (gitdir pointer); the canonical checkout has a
# DIRECTORY.  Installing from a worktree points the command at a checkout
# that may be deleted.
if [ -e "$repo_root/.git" ] && [ ! -d "$repo_root/.git" ]; then
  if [ "${{1:-}}" != "--force" ]; then
    echo "REFUSING: $repo_root is a linked git worktree, not the canonical checkout." >&2
    echo "  pass --force to override." >&2
    exit 2
  fi
  echo "  --force given: installing from a worktree anyway." >&2
fi
echo "  resolved repo root: $repo_root"

begin="# >>> pmoves {tool.launcher_basename} >>>"
end="# <<< pmoves {tool.launcher_basename} <<<"

# Function body emitted into the user's rc file.  The per-node pin entries
# follow it (they each call the canonical function).
fn_body=$(cat <<EOF
$begin
# Auto-generated by install-{tool.launcher_basename}.sh.
# Purpose: {tool.purpose}
{tool.launcher_basename}() {{ "$launcher" "$@"; }}
{pin_block_functions}
$end
EOF
)

install_into() {{
  local rc="$1"
  touch "$rc"
  local tmp; tmp="$(mktemp)"
  awk -v b="$begin" -v e="$end" '
    $0==b {{skip=1}}
    skip!=1 {{print}}
    $0==e {{skip=0}}
  ' "$rc" > "$tmp" && mv "$tmp" "$rc"
  printf '\\n%s\\n' "$fn_body" >> "$rc"
  echo "  updated: $rc"
}}

# Resolve the login shell's rc first (zsh vs bash) so a fresh rc-less shell
# of the active shell still gets the function.
case "$(basename "${{SHELL:-bash}}")" in
  zsh) active_rc="$HOME/.zshrc" ;;
  *)   active_rc="$HOME/.bashrc" ;;
esac

installed=0
for rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
  if [ -f "$rc" ]; then install_into "$rc"; installed=1; fi
done
if [ ! -f "$active_rc" ]; then install_into "$active_rc"; installed=1; fi

# PATH symlink (mirrors install-claude-pmoves-command.sh:88-96)
bindir="$HOME/.local/bin"
mkdir -p "$bindir"
ln -sf "$launcher" "$bindir/{tool.launcher_basename}"
echo "  path symlink: $bindir/{tool.launcher_basename}"
case ":${{PATH}}:" in
  *":$bindir:"*) : ;;
  *) echo "  NOTE: $bindir is not on PATH -- add it, or use the rc function above." ;;
esac

echo ""
echo "Installed '{tool.launcher_basename}' -> $launcher"
{pin_install_echo}echo "Run:  source ~/.bashrc   (or open a new shell)   then just type:  {tool.launcher_basename}"
"""


def _render_install_bash_pins(tool: CliTool, identities: list[NodeIdentity]) -> str:
    """Human-readable listing for the header docstring."""
    if not identities:
        return f"#   (none -- this CLI is not bound to per-node identities in agent_registry.yaml)"
    return "\n".join(f"#   {tool.launcher_basename}-{_pin_label(i)} (PMOVES_NODE_ID={i.node_id})"
                       for i in identities)


def _pin_label(identity: NodeIdentity) -> str:
    """The suffix for `<cli>-<node>` pin files.  Strip `_` to match the
    conventional naming on the deck (claude-4090, not claude-4090-claude).
    """
    suffix = identity.agent_id
    if suffix.startswith(identity.parent_tool + "_"):
        suffix = suffix[len(identity.parent_tool) + 1:]
    return suffix


def _render_install_bash_pin_functions(tool: CliTool, identities: list[NodeIdentity]) -> str:
    if not identities:
        return ""
    lines: list[str] = []
    for ident in identities:
        suffix = _pin_label(ident)
        # Each pin sets PMOVES_NODE_ID and calls the canonical launcher.
        lines.append(
            f"{tool.launcher_basename}-{suffix}() "
            f"{{ PMOVES_NODE_ID=\"{ident.node_id}\" \"${{PMOVES_LAUNCHER_ROOT:-}}\"; "
            f"PMOVES_NODE_ID=\"{ident.node_id}\" \"{tool.launcher_basename}\" \"$@\"; }}"
        )
    return "\n".join(lines)


def render_install_powershell(tool: CliTool, identities: list[NodeIdentity]) -> str:
    """Generate the PowerShell install script (profile function + PATH shim)."""
    pin_block = _render_install_powershell_pins(identities)
    pin_functions = _render_install_powershell_pin_functions(tool, identities)
    pin_aftermath = ""
    if identities:
        names = ", ".join(f"'{tool.launcher_basename}-{_pin_label(i)}'" for i in identities)
        pin_aftermath = f'Write-Host "Also installed: {names}"\n'
    header = GENERATOR_HEADER_PWSH.format(ver=GENERATOR_VERSION)
    return f"""{header}
# install-{tool.launcher_basename}.ps1
# ---------------------------------------------------------------------------
# Makes `{tool.launcher_basename}` a bare command in PowerShell on THIS node,
# so you can type `{tool.launcher_basename}` from any directory instead of the
# full launcher path.  Mirrors install-claude-pmoves-command.ps1 exactly.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File deploy\\provision\\install-{tool.launcher_basename}.ps1
#
# Per-node pin functions (set $env:PMOVES_NODE_ID before calling the launcher):
{pin_block}
# ---------------------------------------------------------------------------
param([switch]$Force)

$ErrorActionPreference = "Stop"

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\\..")).Path
$cmd = Join-Path $repoRoot "deploy\\provision\\{tool.launcher_basename}.cmd"
if (-not (Test-Path $cmd)) {{ throw "launcher not found: $cmd (is this the pmoves repo?)" }}

# Refuse linked worktrees (mirror install-claude-pmoves-command.ps1:32-51).
$gitPath = Join-Path $repoRoot ".git"
if ((Test-Path $gitPath) -and -not (Test-Path $gitPath -PathType Container)) {{
    Write-Host ""
    Write-Host "REFUSING: this is a linked git worktree, not the canonical checkout." -ForegroundColor Red
    if (-not $Force) {{ exit 2 }}
    Write-Host "  -Force given: installing from a worktree anyway." -ForegroundColor Yellow
}}
Write-Host "  resolved repo root: $repoRoot"

$begin = "# >>> pmoves {tool.launcher_basename} >>>"
$end   = "# <<< pmoves {tool.launcher_basename} <<<"
$block = @"
$begin
# Auto-generated by install-{tool.launcher_basename}.ps1.
# Purpose: {tool.purpose}
function {tool.launcher_basename} {{ & "$cmd" @args }}
{pin_functions}
$end
"@

$docs = [Environment]::GetFolderPath('MyDocuments')
$targets = @(
    (Join-Path $docs "WindowsPowerShell\\profile.ps1"),
    (Join-Path $docs "PowerShell\\profile.ps1")
) | Select-Object -Unique

foreach ($profilePath in $targets) {{
    $dir = Split-Path -Parent $profilePath
    if (-not (Test-Path $dir)) {{ New-Item -ItemType Directory -Force -Path $dir | Out-Null }}
    $content = ""
    if (Test-Path $profilePath) {{ $content = Get-Content -Raw -Path $profilePath -ErrorAction SilentlyContinue }}
    if ($null -eq $content) {{ $content = "" }}
    $pattern = [regex]::Escape($begin) + "[\\s\\S]*?" + [regex]::Escape($end)
    $content = [regex]::Replace($content, $pattern, "").TrimEnd()
    if ($content.Length -gt 0) {{ $content += "`r`n`r`n" }}
    $content += $block + "`r`n"
    Set-Content -Path $profilePath -Value $content -Encoding UTF8
    Write-Host "  profile: $profilePath"
}}

# PATH shim (mirrors install-claude-pmoves-command.ps1:88-101).
$shimDir = Join-Path $env:LOCALAPPDATA 'Microsoft\\WindowsApps'
if (Test-Path $shimDir) {{
    $shim = Join-Path $shimDir '{tool.launcher_basename}.cmd'
    $q = [char]34
    $lines = @('@echo off', ('call ' + $q + $cmd + $q + ' %*'))
    Set-Content -Path $shim -Value $lines -Encoding ASCII
    Write-Host "  path shim: $shim"
}} else {{
    Write-Warning "  $shimDir not present - PATH shim skipped (profile function still installed)."
}}

Write-Host ''
Write-Host "Installed '{tool.launcher_basename}' -> $cmd"
{pin_aftermath}
Write-Host 'Works in any NEW shell (PATH shim). In an existing session, open a new shell.'
"""


def _render_install_powershell_pins(identities: list[NodeIdentity]) -> str:
    if not identities:
        return "#   (none -- this CLI is not bound to per-node identities in agent_registry.yaml)"
    return "\n".join(f"#   {i.parent_tool}-pmoves-{_pin_label(i)} ($env:PMOVES_NODE_ID={i.node_id})"
                       for i in identities)


def _render_install_powershell_pin_functions(tool: CliTool,
                                              identities: list[NodeIdentity]) -> str:
    if not identities:
        return ""
    lines: list[str] = []
    for ident in identities:
        suffix = _pin_label(ident)
        lines.append(
            f"function {tool.launcher_basename}-{suffix} {{\n"
            f"    $env:PMOVES_NODE_ID = '{ident.node_id}'\n"
            f"    & {tool.launcher_basename} @args\n"
            f"    Remove-Item Env:PMOVES_NODE_ID -ErrorAction SilentlyContinue\n"
            f"}}"
        )
    return "\n".join(lines)


