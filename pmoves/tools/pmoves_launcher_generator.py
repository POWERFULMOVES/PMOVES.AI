#!/usr/bin/env python3
# pmoves_launcher_generator.py
# ============================================================================
# PMOVES Registry-Driven Launcher Generator
#
# Single source of truth for the Windows-Aware launcher trio (`.sh` / `.ps1` /
# `.cmd`) and the install scripts that put them on PATH, generated FROM the
# registry (`pmoves/configs/cli_tools.yaml` :: `pmoves_wrappers` for the CLI
# list and `pmoves/config/agent_registry.yaml` for per-node identities).
#
# Why this exists:
#   claude-pmoves and crush-pmoves were hand-written; the rest of the
#   pmoves_wrapper roster (codex, kilo, kimi, hermes) had a `pmoves/scripts/`
#   bash wrapper but no Windows-aware `.cmd`/`.ps1` and no installer -- so
#   they could not be double-clicked from Windows Explorer or bare-named in a
#   PowerShell session.  Hand-writing five more would re-create the drift
#   that already shipped (the symlink-walk bug that test-launcher-root-
#   resolution.sh now pins: three launchers carrying the same block, two of
#   them fixed, one not).
#
# What it emits, under `deploy/provision/`:
#   <cli>-pmoves.sh  + .ps1  + .cmd                          (canonical launcher)
#   install-<cli>-pmoves-command.sh  + .ps1                  (rc/profile installer)
#   <cli>-<node>.sh + .ps1 + .cmd    [per-node pin]          (when registry has a multi-node identity)
#   launchers.manifest.json                                   (registry-driven inventory + sha256)
#
# What it does NOT do (out of scope):
#   - Touch the existing hand-written claude-pmoves.{sh,ps1,cmd} /
#     crush-pmoves.{sh,ps1,cmd}.  Those carry SDK-fixed FAIL-CLOSED MCP
#     roster logic (PR #2847 + #2809) that the simple template cannot
#     reproduce.  They are listed in the manifest as `managed_by: hand`.
#   - Touch the `pmoves/scripts/` bash wrappers.  That surface is a separate
#     concern (npm/PATH wrappers); this generator emits the Windows-aware
#     trio.
#
# SDK + doc provenance:
#   - Claude Code CLI:    `--mcp-config <file>` (project scope) per
#     https://docs.claude.com/en/api/agent-sdk/overview.  Hand-written
#     `claude-pmoves.sh` already implements this; the generator just mirrors
#     the same shell-and-PowerShell shape for the other CLIs.
#   - Wezterm `set-pane-environment-variables` is the canonical pattern for
#     binding env to a session surface; the per-node pin files are the
#     PMOVES equivalent (PMOVES_NODE_ID before the canonical launcher).
#   - Windows PATH shim via `%LOCALAPPDATA%\Microsoft\WindowsApps` mirrors
#     the existing `install-claude-pmoves-command.ps1` recipe (lines 88-101).
#
# Run:
#   python pmoves/tools/pmoves_launcher_generator.py --out deploy/provision
#   python pmoves/tools/pmoves_launcher_generator.py --check            # diff against checked-in
#   python pmoves/tools/pmoves_launcher_generator.py --dry-run --json   # see what would emit
# ============================================================================

