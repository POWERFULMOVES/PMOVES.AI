def _load_yaml(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def _family_of(wrapper_name: str) -> str:
    """Return the bare tool family from a wrapper name like `claude-pmoves` -> `claude`.

    Mirrors CliTool.family; duplicated here as a free function because the
    loader needs it BEFORE a CliTool exists.
    """
    return wrapper_name[:-len("-pmoves")] if wrapper_name.endswith("-pmoves") else wrapper_name


def load_cli_tools(registry_root: Path) -> list[CliTool]:
    """Read pmoves/configs/cli_tools.yaml :: pmoves_wrappers."""
    cli_yaml = _load_yaml(registry_root / "pmoves" / "configs" / "cli_tools.yaml")
    wrappers = cli_yaml.get("pmoves_wrappers", {}) or {}
    tools: list[CliTool] = []
    for name, entry in wrappers.items():
        if not isinstance(entry, dict):
            continue
        tool = CliTool(
            name=name,
            purpose=str(entry.get("purpose", "")).strip(),
            binary=BINARY_BY_TOOL.get(_family_of(name), _family_of(name)),
            blocklist=list(DEFAULT_BLOCKLIST_BY_TOOL.get(name, [])),
            bridges=list(DEFAULT_BRIDGES_BY_TOOL.get(name, [])),
            signature_aliases=list(DEFAULT_SIGNATURE_ALIASES.get(_family_of(name), [name])),
            managed="hand" if name in ("claude-pmoves", "crush-pmoves") else "generator",
            script_path=entry.get("script"),
        )
        tools.append(tool)
    return tools


def load_node_identities(registry_root: Path, tools: list[CliTool]) -> list[NodeIdentity]:
    """Read pmoves/config/agent_registry.yaml and find per-CLI identities.

    Match precedence (in order, first hit wins):
      1. `signature == any of CliTool.signature_aliases`
         (crush_glm52.signature="crush", kilocode_glm.signature="kilocode")
      2. `signature` ends with `-<family>` (the Claude per-node signing
         convention: 4090-claude, b850-claude bind to family `claude`)

    Plus a UI/agent surface check: no listening port (CLI session, not
    service).  Each match becomes a per-node pin file
    (`<cli>-<node>.{sh,ps1,cmd}`) that sets `PMOVES_NODE_ID=<node_affinity[0]>`
    and calls the canonical launcher.
    """
    agents = _load_yaml(registry_root / "pmoves" / "config" / "agent_registry.yaml")
    entries = (agents.get("agents") or {})
    # signature -> family lookup (exact match)
    sig_to_family: dict[str, str] = {}
    for t in tools:
        for alias in t.signature_aliases:
            sig_to_family[alias] = t.family

    def family_for_sig(sig_s: str) -> str | None:
        if sig_s in sig_to_family:
            return sig_to_family[sig_s]
        # Claude-style: `4090-claude` -> `claude`
        for t in tools:
            if sig_s.endswith("-" + t.family):
                return t.family
        return None

    out: list[NodeIdentity] = []
    for agent_id, entry in entries.items():
        if not isinstance(entry, dict):
            continue
        sig = entry.get("signature")
        if not sig:
            continue
        sig_s = str(sig)
        family = family_for_sig(sig_s)
        if not family:
            continue
        port = entry.get("port")
        if port is not None:
            continue   # it has a listening socket -> it's a service, not a CLI session
        affinity = (entry.get("topology") or {}).get("node_affinity") or []
        if not affinity:
            continue
        out.append(NodeIdentity(
            agent_id=agent_id,
            parent_tool=family,
            node_id=str(affinity[0]),
            signature=sig_s,
            description=str(entry.get("description") or "").splitlines()[0].strip(),
        ))
    return out


