def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="pmoves_launcher_generator",
        description="Registry-driven generator for deploy/provision/<cli>-pmoves.{sh,ps1,cmd} "
                    "+ install scripts + per-node pin files.",
    )
    p.add_argument("--registry-root", type=Path, default=Path.cwd(),
                   help="Repo root containing pmoves/configs and pmoves/config (default: cwd)")
    p.add_argument("--out", type=Path, default=None,
                   help="Output root for emitted files (default: registry-root)")
    p.add_argument("--check", action="store_true",
                   help="Diff against checked-in files; exit non-zero on drift")
    p.add_argument("--dry-run", action="store_true",
                   help="Print the emission plan without writing files")
    p.add_argument("--json", action="store_true",
                   help="Machine-readable output (combine with --dry-run)")
    p.add_argument("--include-hand", action="store_true",
                   help="Include hand-written launchers in the manifest (for drift pinning)")
    p.add_argument("--tool", action="append", default=[],
                   help="Restrict emission to one or more CLI tool names (repeatable)")
    return p


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    registry_root = args.registry_root.resolve()
    out_root = (args.out or registry_root).resolve()

    plan = build_plan(registry_root, include_hand=args.include_hand)

    if args.tool:
        wanted = set(args.tool)
        plan.files = [f for f in plan.files
                      if any(t for t in wanted if t in f.relpath)]
        plan.tools = [t for t in plan.tools if t.name in wanted]
        plan.identities = [i for i in plan.identities if i.parent_tool in wanted]

    if args.dry_run:
        if args.json:
            print(json.dumps(plan.manifest_dict(), indent=2, sort_keys=True))
        else:
            print(f"== plan: {len(plan.tools)} tools, {len(plan.identities)} identities, "
                  f"{len(plan.files)} files ==")
            for f in plan.files:
                kind = "exec" if f.executable else "    "
                print(f"  {kind} {f.relpath}  ({len(f.body)} bytes)")
        return 0

    if args.check:
        n, diffs = check(plan, registry_root)
        if diffs:
            for d in diffs:
                print(d)
            print(f"\n{n} drift(s) detected -- run without --check to regenerate.")
            return 1
        print(f"All {len(plan.files)} generator files match the checked-in copies.")
        return 0

    written = emit(plan, out_root, plan_root=registry_root)
    print(f"Emitted {len(written)} files under {out_root}/")
    for f in written:
        print(f"  {f.relative_to(out_root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
