def build_plan(registry_root: Path, include_hand: bool = False) -> Plan:
    """Load the registries and produce the full emission plan.

    If `include_hand` is True, list the hand-written launchers in the
    manifest (managed_by=hand) so the drift check can verify the SDK-fixed
    hand files stay byte-stable across regen runs.  Default False keeps
    the manifest focused on generator output.
    """
    tools = load_cli_tools(registry_root)
    identities = load_node_identities(registry_root, tools)
    plan = Plan(tools=tools, identities=identities)

    for tool in tools:
        tool_idents = [i for i in identities if i.parent_tool == tool.family]
        is_hand = tool.managed == "hand"

        # --- install scripts -------------------------------------------------
        # ONLY emit when the launcher is generator-managed.  For hand-managed
        # tools (claude, crush), the install scripts are SDK-fixed and live
        # in the repo; the operator updates them by hand if they want
        # per-node pin registration.  Overwriting them silently would lose
        # the worktree-refusal guard, the PATH shim recipe, etc.
        if not is_hand:
            rel_ins_sh = f"deploy/provision/{tool.install_basename}.sh"
            rel_ins_ps1 = f"deploy/provision/{tool.install_basename}.ps1"
            body_ins_sh = render_install_bash(tool, tool_idents)
            body_ins_ps1 = render_install_powershell(tool, tool_idents)
            plan.files.extend([
                GeneratedFile(rel_ins_sh, body_ins_sh, executable=True,
                              managed_by="generator"),
                GeneratedFile(rel_ins_ps1, body_ins_ps1, executable=False,
                              managed_by="generator"),
            ])
        elif include_hand:
            # --include-hand: surface the install scripts in the manifest for
            # drift pinning, but emit them too (operator is explicitly asking
            # for the SDK-fixed hand files to be rewritten -- usually a no-no).
            rel_ins_sh = f"deploy/provision/{tool.install_basename}.sh"
            rel_ins_ps1 = f"deploy/provision/{tool.install_basename}.ps1"
            plan.files.extend([
                GeneratedFile(rel_ins_sh, render_install_bash(tool, tool_idents),
                              executable=True, managed_by="hand"),
                GeneratedFile(rel_ins_ps1, render_install_powershell(tool, tool_idents),
                              executable=False, managed_by="hand"),
            ])

        # --- canonical launcher trio (.sh/.ps1/.cmd) -------------------------
        # Hand-managed: emit ONLY with --include-hand (drift pinning).
        # Generator-managed: always emit.
        if not is_hand or include_hand:
            rel_sh = f"deploy/provision/{tool.launcher_basename}.sh"
            rel_ps1 = f"deploy/provision/{tool.launcher_basename}.ps1"
            rel_cmd = f"deploy/provision/{tool.launcher_basename}.cmd"
            body_sh = render_bash_launcher(tool)
            body_ps1 = render_powershell_launcher(tool)
            body_cmd = render_cmd_wrapper(tool)
            plan.files.extend([
                GeneratedFile(rel_sh, body_sh, executable=True,
                              managed_by="hand" if is_hand else "generator"),
                GeneratedFile(rel_ps1, body_ps1, executable=False,
                              managed_by="hand" if is_hand else "generator"),
                GeneratedFile(rel_cmd, body_cmd, executable=False,
                              managed_by="hand" if is_hand else "generator"),
            ])

        # --- per-node pin files ---------------------------------------------
        # ALWAYS emit for every multi-node identity, regardless of hand vs
        # generator status.  These are NEW callers of the canonical launcher
        # (which may be hand-written) -- they do not duplicate it.
        for ident in tool_idents:
            rel_pin_sh = f"deploy/provision/{ident.launcher_basename}.sh"
            rel_pin_ps1 = f"deploy/provision/{ident.launcher_basename}.ps1"
            rel_pin_cmd = f"deploy/provision/{ident.launcher_basename}.cmd"
            plan.files.extend([
                GeneratedFile(rel_pin_sh, render_pin_bash(tool, ident), executable=True),
                GeneratedFile(rel_pin_ps1, render_pin_powershell(tool, ident), executable=False),
                GeneratedFile(rel_pin_cmd, render_pin_cmd(tool, ident), executable=False),
            ])
    return plan


# ----------------------------------------------------------------------------
# Emitter
# ----------------------------------------------------------------------------

def emit(plan: Plan, out_root: Path, plan_root: Path | None = None) -> list[Path]:
    """Write every file in `plan` to `out_root`.  Returns the list of paths
    actually written.  Idempotent: re-running yields byte-identical output.
    """
    written: list[Path] = []
    base = plan_root if plan_root is not None else Path.cwd()
    # Line endings per repo policy (.gitattributes): ps1/bat/cmd are
    # eol=crlf (Windows scripts), everything else eol=lf. emit() must write
    # what the worktree will contain after checkout conversion, or the
    # byte-stability test compares CRLF (repo checkout) against LF (regen)
    # and fails on EVERY platform — the blob is LF in git, the attribute
    # converts at checkout, the generator must match the attribute.
    def _eol(relpath: str) -> str:
        return "\r\n" if relpath.endswith((".ps1", ".bat", ".cmd")) else "\n"
    for f in plan.files:
        target = out_root / f.relpath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(f.body, encoding="utf-8", newline=_eol(f.relpath))
        if f.executable:
            mode = target.stat().st_mode
            target.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        written.append(target)
    # Always emit the manifest, even when `out_root == plan_root`, so
    # downstream drift-check consumers have a single anchor.
    manifest_target = out_root / "deploy" / "provision" / "launchers.manifest.json"
    manifest_target.parent.mkdir(parents=True, exist_ok=True)
    manifest_target.write_text(
        json.dumps(plan.manifest_dict(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8", newline="\n",
    )
    return written


def check(plan: Plan, repo_root: Path) -> tuple[int, list[str]]:
    """Compare `plan` against what's currently on disk.  Returns (count of
    mismatches, list of human-readable diff messages)."""
    diffs: list[str] = []
    for f in plan.files:
        on_disk = repo_root / f.relpath
        if not on_disk.exists():
            diffs.append(f"MISSING  {f.relpath}")
            continue
        disk_body = on_disk.read_text(encoding="utf-8")
        if disk_body != f.body:
            disk_hash = hashlib.sha256(disk_body.encode("utf-8")).hexdigest()
            gen_hash = hashlib.sha256(f.body.encode("utf-8")).hexdigest()
            diffs.append(f"DIFFER   {f.relpath}  disk={disk_hash[:12]} gen={gen_hash[:12]}")
    # Check the manifest too (it is itself generated)
    manifest_path = repo_root / "deploy" / "provision" / "launchers.manifest.json"
    expected_manifest = json.dumps(plan.manifest_dict(), indent=2, sort_keys=True) + "\n"
    if manifest_path.exists():
        disk_manifest = manifest_path.read_text(encoding="utf-8")
        if disk_manifest != expected_manifest:
            diffs.append(f"DIFFER   deploy/provision/launchers.manifest.json")
    else:
        diffs.append(f"MISSING  deploy/provision/launchers.manifest.json")
    return len(diffs), diffs


