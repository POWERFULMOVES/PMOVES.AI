# Template: bash launcher (.sh)
# ----------------------------------------------------------------------------

def render_bash_launcher(tool: CliTool) -> str:
    """Generate a bash launcher that sources env.shared and execs the binary."""
    blocklist_re = _bash_blocklist_regex(tool.blocklist)
    bridges_block = _render_bridges_bash(tool.bridges)
    # AWK_INVOCATION: replace every single quote with the 4-char bash
    # idiom `'\''` (close single-quote, escaped quote, open new quote).
    # Built in Python so we never nest backslash escapes inside the f-string
    # template body (which breaks both Python f-string parsing and the
    # resulting bash syntax -- see PR conversation 2026-09-16).
    awk_sq_program = '{ gsub(/\\047/, "\\047\\\\\\047\\047"); print }'
    awk_invocation = f"awk '{awk_sq_program}'"
    header = GENERATOR_HEADER_BASH.format(ver=GENERATOR_VERSION)
    body = f"""{header}
# {tool.launcher_basename}.sh -- launch `{tool.binary}` with pmoves/env.shared loaded
# ===========================================================================
# Auto-generated wrapper for {tool.name}. Mirrors the hand-written
# claude-pmoves.sh / crush-pmoves.sh SHELL pattern (resolve repo root via
# symlink-walk, source env.shared, exec the binary) so every pmoves_wrapper
# has the same Windows + POSIX entry surface and the same env-loaded
# preconditions.  The hand-written launchers carry SDK-fixed FAIL-CLOSED
# MCP roster logic this template does not reproduce -- that is by design.
#
# Usage:
#   bash deploy/provision/{tool.launcher_basename}.sh        [args...]
#   install-{tool.name}-pmoves-command.sh && {tool.launcher_basename}         # rc function
#   {tool.launcher_basename}.cmd                              # Windows Explorer double-click
#
# Purpose: {tool.purpose}
#
# Override env.shared path with PMOVES_ENV_SHARED.
set -u

# --- REPO-ROOT RESOLUTION (mirror claude-pmoves.sh) -------------------------
# See test-launcher-root-resolution.sh for why this walk must stay byte-
# identical across every launcher that carries it: an installer symlink at
# ~/.local/bin/<name> would otherwise make ROOT=$HOME and env.shared miss.
SELF="${{BASH_SOURCE[0]:-$0}}"
while [ -L "$SELF" ]; do
  link_dir="$(CDPATH='' cd -P -- "$(dirname -- "$SELF")" && pwd)"
  SELF="$(readlink -- "$SELF")"
  case "$SELF" in /*) ;; *) SELF="$link_dir/$SELF" ;; esac
done
SELF_DIR="$(CDPATH='' cd -P -- "$(dirname -- "$SELF")" && pwd)"
if [ -n "${{PMOVES_LAUNCHER_ROOT:-}}" ]; then
  ROOT="$PMOVES_LAUNCHER_ROOT"
else
  ROOT="$(CDPATH='' cd -P -- "$SELF_DIR/../.." && pwd)" || ROOT=""
fi
if [ ! -f "${{ROOT:-/nonexistent}}/pmoves/Makefile" ]; then
  if [ -n "${{PMOVES_ENV_SHARED:-}}" ] && [ -f "$PMOVES_ENV_SHARED" ]; then
    echo "[{tool.launcher_basename}] WARN: repo root not found (${{ROOT:-<unresolved>}}); using PMOVES_ENV_SHARED." >&2
  else
    echo "[{tool.launcher_basename}] ERROR: no pmoves/Makefile under repo root: ${{ROOT:-<unresolved>}}" >&2
    echo "[{tool.launcher_basename}]        (resolved from: $SELF)" >&2
    exit 1
  fi
fi

# --- MAVIS SDK ENV STRIP ---------------------------------------------------
# The Mavis SDK's `env` block in `~/.claude/settings.json` injects
# ANTHROPIC_BASE_URL, ANTHROPIC_AUTH_TOKEN, ANTHROPIC_MODEL, MCP_TIMEOUT,
# API_TIMEOUT_MS, CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC, ... into every
# Claude Code session's process env.  That env block is inherited by the
# shell that runs this launcher, and would otherwise be inherited by the
# launched `{tool.binary}` -- overriding the operator's own CLI settings
# (their API endpoint, their model picker).
#
# The strip checks each Mavis SDK var against `{tool.binary}`'s NEEDS list
# (defined in pmoves/scripts/mavis_sdk_env.sh alongside this comment):
#   * keeps the ones `{tool.binary}` consumes
#   * preserves the others under PMOVES_MAVIS_SDK_<NAME> for inspection
#   * unsets the originals
#   * emits one WARN line summarizing what was caught
#
# Sourced AFTER repo-root resolution (helper file is repo-relative) and
# BEFORE env.shared loading (the env.shared reader below has a parallel
# blocklist for env.shared itself; the two layers cover the SHELL env and
# env.shared independently).
# ---------------------------------------------------------------------------
if [ -f "$ROOT/pmoves/scripts/mavis_sdk_env.sh" ]; then
  # shellcheck source=../../pmoves/scripts/mavis_sdk_env.sh
  . "$ROOT/pmoves/scripts/mavis_sdk_env.sh"
  mavis_sdk_strip_env_for "{tool.family}"
else
  echo "[{tool.launcher_basename}] WARN: mavis_sdk_env.sh not found at $ROOT/pmoves/scripts/ -- Mavis SDK env may bleed into the launched session." >&2
fi

# --- ENV.SHARED LOADING (mirror claude-pmoves.sh :: lines 72-127) -----------
# env.shared is Docker Compose env_file format: unquoted values + ALIAS lines
# like `SUPABASE_SERVICE_ROLE_KEY=${{SERVICE_ROLE_KEY}}`.  Two hazards:
#   1. We can't `source` it raw -- unquoted values break `. file`.
#   2. We must NOT export values verbatim -- that leaks the literal string
#      "${{SERVICE_ROLE_KEY}}" into MCP headers and starts them unauthorized.
# Build a sanitized assignment file (single-quote plain values; pass ${{...}}-
# bearing lines through for shell expansion), then source it auto-export.
ENVF="${{PMOVES_ENV_SHARED:-$ROOT/pmoves/env.shared}}"
if [ -f "$ENVF" ]; then
  blocklist='{blocklist_re}'
  set +H 2>/dev/null || true
  tmpf=$(mktemp)
  n=0
  while IFS= read -r line || [ -n "$line" ]; do
    line="${{line%$'\\r'}}"
    case "$line" in ''|\\#*) continue;; esac
    case "$line" in *=*) : ;; *) continue;; esac
    key=${{line%%=*}}
    val=${{line#*=}}
    key=$(printf '%s' "$key" | tr -d '[:space:]')
    [ -z "$key" ] && continue
    if [[ "$key" =~ $blocklist ]]; then continue; fi
    val="${{val#"${{val%%[![:space:]]*}}"}}"
    # Two-pass expansion: pass literal `${{...}}` lines through verbatim
    # so the shell expands them on `. "$tmpf"`.  Otherwise single-quote
    # so the literal value lands in the env (avoid the placeholder leak
    # Codex #1987 P2 caught).  Mirror pmoves/scripts/with-env.sh.
    #
    # Single-quote escape routes through awk octal (\\047) -- never nest
    # `\\''` literals (loses count in f-string backslash escapes; see
    # PR conversation 2026-09-16 + pmoves_launcher_generator_LEARNINGS.md).
    if printf '%s' "$val" | grep -qE '[$]{{'; then
      printf '%s=%s\\n' "$key" "$val" >> "$tmpf"
    else
      esc=$(printf '%s' "$val" | {awk_invocation})
      printf "%s='%s'\\n" "$key" "$esc" >> "$tmpf"
    fi
    n=$((n+1))
  done < "$ENVF"
  set -a; set +u
  . "$tmpf"
  set +a; set -u
  rm -f "$tmpf"
  set -H 2>/dev/null || true
  echo "[{tool.launcher_basename}] loaded $n vars from $ENVF" >&2
else
  echo "[{tool.launcher_basename}] WARN: $ENVF not found -- MCP creds may be missing." >&2
  echo "[{tool.launcher_basename}]       run: make -C pmoves ensure-env-shared" >&2
fi

# --- NAME BRIDGES (operator-facing alias to upstream SDK name) -------------
{bridges_block}

# --- LAUNCH ---------------------------------------------------------------
export PMOVES_LAUNCHER_SESSION="{tool.launcher_basename}.sh"
exec {tool.binary} "$@"
"""
    return body


def _bash_blocklist_regex(blocklist: list[str]) -> str:
    """Build the bash regex for the blocklist.

    We use `^` to anchor on the var name and `\\\\*` to convert `*` (CLAUDE_CODE_*)
    into `.*` for shell regex.  Same format as claude-pmoves.sh:74-78.
    """
    if not blocklist:
        return "^$NEVER_MATCH$"
    parts: list[str] = []
    for entry in blocklist:
        # Escape regex metacharacters EXCEPT `*`, which we translate.
        esc = ""
        for ch in entry:
            if ch == "*":
                esc += ".*"
            elif ch in r".^$+?()[]{}|\\":
                esc += "\\" + ch
            else:
                esc += ch
        parts.append(esc)
    body = "|".join(parts)
    return f"^({body})$"


def _render_bridges_bash(bridges: list[tuple[str, str]]) -> str:
    if not bridges:
        return "# (no name bridges for this CLI)"
    lines = ["# Mirror crush-pmoves.sh:133-136 -- alias bridge for upstream-vs-PMOVES env names.",
             "# Only set when the upstream var is unset, so an explicit operator pin still wins."]
    for from_v, to_v in bridges:
        lines.append(
            f'if [ -z "${{{to_v}:-}}" ] && [ -n "${{{from_v}:-}}" ]; then\n'
            f'  export {to_v}="${{{from_v}}}"\n'
            f'  echo "[{{launcher}}] {to_v} <- {from_v} (upstream/PMOVES name bridge)" >&2\n'
            f'fi'
        )
    return "\n".join(lines).replace("{launcher}", "${{0##*/}}")


