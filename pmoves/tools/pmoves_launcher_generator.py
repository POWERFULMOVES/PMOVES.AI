@dataclass(frozen=True)
class CliTool:
    """One CLI from cli_tools.yaml :: pmoves_wrappers."""
    name: str               # wrapper name as registered (e.g. "kilo-pmoves",
                            # "claude-pmoves") -- already carries "-pmoves" suffix
    purpose: str            # human description from cli_tools.yaml
    binary: str             # actual executable (BINARY_BY_TOOL override)
    blocklist: list[str]    # env vars to NEVER source
    bridges: list[tuple[str, str]]  # (from, to) alias bridges
    signature_aliases: list[str]    # registry `signature` values this tool matches
    managed: str = "generator"  # "generator" (we emit) | "hand" (existing files stay)
    script_path: str | None = None  # pmoves/scripts/* path from cli_tools.yaml

    @property
    def family(self) -> str:
        """Bare tool family (claude / kilo / crush / ...) -- the part before -pmoves.

        Used as the registry `signature` lookup key and as the per-node pin
        file prefix: `claude-4090`, `kilo-5090`, etc.  Always strips the
        `-pmoves` suffix if present (cli_tools.yaml registers them as
        `claude-pmoves`, `kilo-pmoves`).
        """
        return self.name[:-len("-pmoves")] if self.name.endswith("-pmoves") else self.name

    @property
    def launcher_basename(self) -> str:
        """Full wrapper basename used for emit paths -- the cli_tools.yaml name as-is."""
        return self.name

    @property
    def install_basename(self) -> str:
        """Full install script basename (e.g. `install-kilo-pmoves-command.sh`)."""
        return f"install-{self.name}-command"


@dataclass(frozen=True)
class NodeIdentity:
    """One CLI agent identity from agent_registry.yaml."""
    agent_id: str           # registry key (e.g. "claude_4090")
    parent_tool: str        # tool family (e.g. "claude") -- matched by signature
    node_id: str            # PMOVES_NODE_ID to set (registry's node_affinity[0])
    signature: str          # signature from registry (== parent_tool usually)
    description: str        # first line of registry description

    @property
    def launcher_basename(self) -> str:
        """`<cli>-<node>` pin-file basename (e.g. "claude-4090", "kilo-knuckles")."""
        suffix = self.agent_id
        if suffix.startswith(self.parent_tool + "_"):
            suffix = suffix[len(self.parent_tool) + 1:]
        return f"{self.parent_tool}-pmoves-{suffix}"


@dataclass
class GeneratedFile:
    """A file the generator is about to emit."""
    relpath: str            # e.g. "deploy/provision/kilo-pmoves.sh"
    body: str               # full file content (with leading AUTO-GENERATED header)
    executable: bool = False
    managed_by: str = "generator"  # "generator" or "hand"


@dataclass
class Plan:
    """Full emission plan for a given registry snapshot."""
    files: list[GeneratedFile] = field(default_factory=list)
    tools: list[CliTool] = field(default_factory=list)
    identities: list[NodeIdentity] = field(default_factory=list)

    def by_relpath(self, relpath: str) -> GeneratedFile | None:
        for f in self.files:
            if f.relpath == relpath:
                return f
        return None

    def manifest_dict(self) -> dict[str, Any]:
        return {
            "generator_version": GENERATOR_VERSION,
            "tool_count": len(self.tools),
            "identity_count": len(self.identities),
            "files": [
                {
                    "relpath": f.relpath,
                    "sha256": hashlib.sha256(f.body.encode("utf-8")).hexdigest(),
                    "bytes": len(f.body.encode("utf-8")),
                    "executable": f.executable,
                    "managed_by": f.managed_by,
                }
                for f in self.files
            ],
        }


