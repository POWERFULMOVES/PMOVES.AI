#!/usr/bin/env python3
"""Known Roads provenance checker — matrix-backed.

Replaces the wild-string `reason` check in
`.claude/hooks/damage-control/known_roads.py` with a deterministic
service-matrix lookup. The matrix lives at
`pmoves/configs/topology/docker_matrix.yaml` (regenerated by
`build_docker_matrix.py`).

Provenance rule:
  The grant reason for any Edit/Write to a protected path MUST be a
  known-road reference, not a free-text handoff name. The reference
  shape is `pr:N`, `issue:N`, `handoff:NAME.md`, `lifecycle:NAME`, or
  `session:ID`, and the matrix must list the service in the overlay
  that owns the path being edited.

Examples of passing reasons:
  - pr:3050                          (PR reference; the matrix has pr: refs)
  - issue:2974                       (issue reference)
  - handoff:notebook-mcp-build-2026-09-02.md  (handoff reference)

Examples of failing reasons:
  - free-text "I want to add a port"
  - wild strings not in any matrix reference

Usage:
    python pmoves/tools/topology/check_known_roads.py --path PATH --reason REASON --domain DOMAIN
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

MATRIX_PATH = (
    Path(__file__).resolve().parents[2] / "configs" / "topology" / "docker_matrix.yaml"
)

REPO_ROOT = MATRIX_PATH.parents[3]

REFERENCE_PATTERNS = [
    re.compile(r"^pr:\d+$"),
    re.compile(r"^issue:\d+$"),
    re.compile(r"^handoff:[a-z0-9_.-]+\.md$"),
    re.compile(r"^lifecycle:[a-z0-9_.-]+$"),
    re.compile(r"^session:[a-z0-9_-]{8,}$"),
]


def _load_matrix() -> dict:
    if not MATRIX_PATH.exists():
        return {}
    import yaml
    with MATRIX_PATH.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def _normalize_path(path: str) -> str:
    """Repo-relative POSIX form of a caller-supplied path.

    Matrix entries are repo-relative POSIX strings (see
    build_docker_matrix.py), so the gate only ever compares like with
    like. Absolute paths under the repo root are relativized so the
    gate works from any cwd; absolute paths outside the repo root are
    returned as-is and can never match a matrix entry.
    """
    p = Path(path)
    if p.is_absolute():
        try:
            p = p.resolve().relative_to(REPO_ROOT)
        except ValueError:
            return path.replace("\\", "/")
    posix = p.as_posix()
    if posix.startswith("./"):
        posix = posix[2:]
    return posix


def _matrix_owns_path(matrix: dict, path: str) -> list:
    """Match a path to the services that own it.

    Single lookup rule: each service carries an `overlays` list (Source A)
    whose entries hold `paths` — the repo-relative compose files that
    declare the service — plus an optional `guard_paths` list (Source C,
    submodule-resident services) of exact paths the gate accepts. The
    gate passes iff the lookup path matches one of those entries (after
    path normalization).

    No fuzzy substring matches, no directory-shape inference, no
    overlay-file-prefix checks. The matrix is the canonical source, the
    gate is exact. If the gate refuses a path the operator expects to
    pass, the right fix is to add the path to the matrix's
    `guard_paths`, not to soften the gate.
    """
    path = _normalize_path(path)

    owners: list = []
    for svc in matrix.get("services", []):
        # Source A: paths under each overlay entry
        found = False
        for ov_entry in svc.get("overlays") or []:
            for ov_path in ov_entry.get("paths") or []:
                normalized = str(ov_path).replace("\\", "/")
                if normalized == path or path.startswith(normalized):
                    owners.append(svc["name"])
                    found = True
                    break
            if found:
                break
        if not found:
            # Source C: explicit guard_paths set (added by Source C in build)
            guards = {str(g).replace("\\", "/") for g in svc.get("guard_paths") or []}
            if path in guards:
                owners.append(svc["name"])
    return owners


def _reason_has_valid_reference(reason: str) -> bool:
    for tok in reason.split():
        for pat in REFERENCE_PATTERNS:
            if pat.match(tok):
                return True
    for pat in REFERENCE_PATTERNS:
        if pat.match(reason.strip()):
            return True
    return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--path", required=True)
    parser.add_argument("--reason", required=True)
    parser.add_argument("--domain", required=True,
                        help="compose|dockerfile|schema|topic|secrets")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    matrix = _load_matrix()
    if not matrix:
        if args.json:
            print(json.dumps({"ok": False, "reason": "matrix not loaded"}))
        else:
            print(f"known-roads: FAIL - matrix not loaded at {MATRIX_PATH}")
        return 2

    owners = _matrix_owns_path(matrix, args.path)
    if not owners:
        if args.json:
            print(json.dumps({"ok": False, "reason": "no matrix owner for path",
                               "path": args.path}))
        else:
            print(f"known-roads: FAIL - no matrix owner for {args.path}")
        return 1

    if args.domain not in ("compose", "dockerfile", "schema", "topic", "secrets"):
        if args.json:
            print(json.dumps({"ok": False, "reason": "unknown domain"}))
        else:
            print(f"known-roads: FAIL - unknown domain {args.domain!r}")
        return 1

    if not _reason_has_valid_reference(args.reason):
        if args.json:
            print(json.dumps({"ok": False, "reason": "no valid reference token in reason",
                               "got": args.reason}))
        else:
            print(f"known-roads: FAIL - no valid reference token in reason {args.reason!r}")
        return 1

    if args.json:
        print(json.dumps({"ok": True, "owners": owners, "domain": args.domain,
                           "reason": args.reason}))
    else:
        print(f"known-roads: PASS - owners={owners} domain={args.domain} reason={args.reason!r}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
