"""Workflow Templates for Cross-Repository PR Automation

Defines reusable templates for common pull request patterns across
PMOVES.AI repositories.
"""

from typing import Dict, List, Any
from dataclasses import dataclass
from enum import Enum


class PRType(Enum):
    """Types of pull requests."""
    DEPENDENCY_UPDATE = "dependency_update"
    SECURITY_PATCH = "security_patch"
    FEATURE_BACKPORT = "feature_backport"
    RELEASE_AUTOMATION = "release_automation"
    DEPENDABOT = "dependabot"
    VERSION_BUMP = "version_bump"


@dataclass
class PRWorkflowTemplate:
    """Template for automated pull request creation."""
    pr_type: PRType
    title_template: str
    body_template: str
    branch_name_template: str
    labels: List[str]
    reviewers: List[str]
    assignees: List[str]
    auto_merge: bool = False
    merge_method: str = "squash"
    draft: bool = False

    def render_title(self, **kwargs) -> str:
        """Render PR title with variables."""
        return self.title_template.format(**kwargs)

    def render_body(self, **kwargs) -> str:
        """Render PR body with variables."""
        return self.body_template.format(**kwargs)

    def render_branch_name(self, **kwargs) -> str:
        """Render branch name with variables."""
        return self.branch_name_template.format(**kwargs)


