def get_template(pr_type: PRType) -> PRWorkflowTemplate:
    """Get workflow template by PR type.

    Args:
        pr_type: Type of pull request

    Returns:
        PRWorkflowTemplate for the specified type
    """
    if pr_type not in WORKFLOW_TEMPLATES:
        raise ValueError(f"Unknown PR type: {pr_type}")
    return WORKFLOW_TEMPLATES[pr_type]


def list_templates() -> List[Dict[str, Any]]:
    """List all available workflow templates.

    Returns:
        List of template metadata
    """
    return [
        {
            "type": template.pr_type.value,
            "title_example": template.render_title(
                package="example",
                old_version="1.0.0",
                new_version="2.0.0"
            ),
            "branch_example": template.render_branch_name(
                package="example",
                new_version="2.0.0"
            ),
            "labels": template.labels,
            "auto_merge": template.auto_merge,
        }
        for template in WORKFLOW_TEMPLATES.values()
    ]
