"""Generator-emitted shell launchers must stay executable in the git index.

WHAT WAS WRONG
--------------
The PR #3184 merge (a5b0a8238) flipped 18 of the 19 `*.sh` files that
`pmoves/tools/pmoves_launcher_generator.py` emits into `deploy/provision/`
from 100755 to 100644. The merge was made on a Windows checkout, where the
working tree carries no exec bit, so the mode change rode along unnoticed.
Content was untouched, so the generator's `--check` drift gate stayed green.
On the Linux nodes (B850, SPARK, the KVMs) a direct `./claude-pmoves-b850.sh`
then fails with "permission denied"; only `bash <file>` still works.

WHAT THIS TEST HOLDS
--------------------
Every `deploy/provision/*.sh` stamped AUTO-GENERATED by the launcher generator
is 100755 in the git INDEX. It reads `git ls-files -s`, not the filesystem
mode, because the index is what Linux checkouts materialise and a Windows
filesystem cannot report the bit at all.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
PROVISION = REPO_ROOT / "deploy" / "provision"
GENERATOR_STAMP = "AUTO-GENERATED by pmoves/tools/pmoves_launcher_generator.py"


def _generated_launchers() -> list[Path]:
    out = []
    for path in sorted(PROVISION.glob("*.sh")):
        head = path.read_text(encoding="utf-8", errors="replace")[:2048]
        if GENERATOR_STAMP in head:
            out.append(path)
    return out


def _index_modes(paths: list[Path]) -> dict[str, str]:
    rel = [p.relative_to(REPO_ROOT).as_posix() for p in paths]
    proc = subprocess.run(
        ["git", "-C", str(REPO_ROOT), "ls-files", "-s", "--", *rel],
        capture_output=True,
        text=True,
        check=True,
    )
    modes = {}
    for line in proc.stdout.splitlines():
        meta, _, name = line.partition("\t")
        modes[name] = meta.split()[0]
    return modes


@pytest.mark.skipif(shutil.which("git") is None, reason="git not on PATH")
def test_generator_emitted_launchers_are_executable_in_index():
    launchers = _generated_launchers()
    assert launchers, f"no generator-stamped launchers found under {PROVISION}"
    modes = _index_modes(launchers)
    untracked = [p.name for p in launchers if p.relative_to(REPO_ROOT).as_posix() not in modes]
    assert not untracked, f"generator-stamped launchers not tracked by git: {untracked}"
    not_exec = sorted(name for name, mode in modes.items() if mode != "100755")
    assert not not_exec, (
        "generator-emitted launchers lost the exec bit in the git index "
        "(fix: git update-index --chmod=+x <file>): " + ", ".join(not_exec)
    )
